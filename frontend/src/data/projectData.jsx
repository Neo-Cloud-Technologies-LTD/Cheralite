// Helper function to find a project by slug or ID
export const getProjectBySlugOrId = (identifier) => {
  if (!identifier) return null;
  const match = projectData.find(
    (p) =>
      p.slug === identifier ||
      p.id.toString() === identifier.toString() ||
      p.title.toLowerCase().replace(/[^a-z0-9]+/g, '-') === identifier.toLowerCase()
  );
  return match || null;
};
